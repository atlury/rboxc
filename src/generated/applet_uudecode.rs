unsafe extern "C" fn expand_tilde(mut buf: *mut ::core::ffi::c_char) -> *mut ::core::ffi::c_char {
    let mut outname: *mut ::core::ffi::c_char = ::core::ptr::null_mut::<::core::ffi::c_char>();
    let mut homedir: *const ::core::ffi::c_char = ::core::ptr::null::<::core::ffi::c_char>();
    if *buf.offset(1isize) as ::core::ffi::c_int == '/' as ::core::ffi::c_int {
        homedir = get_env_homedir();
        buf = buf.offset(2 as ::core::ffi::c_int as isize);
    } else {
        let mut pw: *mut passwd = ::core::ptr::null_mut::<passwd>();
        let mut pz: *mut ::core::ffi::c_char = buf.offset(1 as ::core::ffi::c_int as isize);
        while *pz as ::core::ffi::c_int != '/' as ::core::ffi::c_int {
            pz = pz.offset(1);
        }
        if *pz as ::core::ffi::c_int == NUL {
            error(
                0 as ::core::ffi::c_int,
                0 as ::core::ffi::c_int,
                aoGetsText(b"%s: Illegal file name: %s\0".as_ptr() as *const ::core::ffi::c_char),
                program_name,
                buf,
            );
            return ::core::ptr::null_mut::<::core::ffi::c_char>();
        }
        let c2rust_fresh3 = pz;
        pz = pz.offset(1);
        *c2rust_fresh3 = NUL as ::core::ffi::c_char;
        pw = getpwnam(buf.offset(1 as ::core::ffi::c_int as isize));
        if pw.is_null() {
            error(
                0 as ::core::ffi::c_int,
                0 as ::core::ffi::c_int,
                aoGetsText(b"No user '%s'\0".as_ptr() as *const ::core::ffi::c_char),
                buf.offset(1 as ::core::ffi::c_int as isize),
            );
            return ::core::ptr::null_mut::<::core::ffi::c_char>();
        }
        homedir = (*pw).pw_dir;
        buf = pz;
    }
    let mut sz: size_t = strlen(homedir)
        .wrapping_add(strlen(buf))
        .wrapping_add(2 as size_t);
    outname = malloc(sz) as *mut ::core::ffi::c_char;
    if outname.is_null() {
        fserr(
            uudecode_exit_code_t::UUDECODE_EXIT_NO_MEM.0 as ::core::ffi::c_int,
            b"malloc\0".as_ptr() as *const ::core::ffi::c_char,
            aoGetsText(b"output file name\0".as_ptr() as *const ::core::ffi::c_char),
        );
    }
    sprintf(
        outname,
        b"%s/%s\0".as_ptr() as *const ::core::ffi::c_char,
        homedir,
        buf,
    );
    return outname;
}
